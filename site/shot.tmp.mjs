import { chromium, webkit } from '@playwright/test';
const [,, url, out, w='390', h='844', full='0', engine='chromium'] = process.argv;
const b = await (engine==='webkit'?webkit:chromium).launch();
const p = await b.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2, hasTouch: +w<800, isMobile: engine!=='webkit' && +w<800 });
const errs=[]; p.on('console', m => { if (m.type()==='error') errs.push(m.text()); }); p.on('pageerror', e => errs.push(String(e)));
await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(1200);
const ov = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth);
await p.screenshot({ path: out, fullPage: full==='1' });
console.log('overflow', ov, 'errors', JSON.stringify(errs));
await b.close();
